;------------------------------------------------------------------------------
; int AddSubI32_a(int a, int b, int c, int d);
;------------------------------------------------------------------------------

section .text
global _AddSubI32_a
_AddSubI32_a:

; Calculate (a + b) - (c + d) + 7
    add edi, esi            ;edi = a + b
    add edx, ecx            ;edx = c + d
    mov eax, 7
    sub edi, edx            ;edi = (a + b) - (c + d)
    add eax, edi            ;eax = (a + b) - (c + d) + 7

    ret                     ;return to caller
